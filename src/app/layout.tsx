import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { Providers } from "@/components/providers";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Stellar Portfolio Rebalancer",
  description:
    "Automated portfolio rebalancing on Stellar - non-custodial, threshold-triggered, live on testnet.",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
      // Stellar Wallets Kit writes its own theming CSS vars onto <html> on
      // init, which differs from the server-rendered markup - the standard
      // escape hatch for a third-party script mutating this element before
      // hydration (same as a theme-detection script would need).
      suppressHydrationWarning
    >
      <body className="min-h-full flex flex-col">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
